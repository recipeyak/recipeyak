CREATE FUNCTION public.notify_index_updated() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    notify recipe_enqueued_for_indexing;
    RETURN NEW;
END;
$$;

CREATE FUNCTION public.update_core_ingredient_indexing() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN
        INSERT INTO recipe_index_queue (created, modified, recipe_id, deleted)
        VALUES (now(), now(), NEW.recipe_id, false);
    ELSEIF TG_OP = 'DELETE' THEN
        INSERT INTO recipe_index_queue (created, modified, recipe_id, deleted)
        VALUES (now(), now(), OLD.recipe_id, true);
    END IF;
    RETURN NEW;
END;
$$;

